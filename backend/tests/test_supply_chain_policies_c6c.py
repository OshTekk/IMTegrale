@pytest.mark.parametrize("invalid", ["wildcard", "duplicate", "extra_field", "bad_sha"])
def test_binary_allowlist_schema_is_strict(
    tmp_path: Path,
    scanner: ModuleType,
    invalid: str,
) -> None:
    payload = b"wOFF" + b"\x00" * 32
    entry = _binary_entry(payload, ["vendor.woff"])
    entries = [entry]
    if invalid == "wildcard":
        entry["allowed_paths"] = ["*.woff"]
    elif invalid == "duplicate":
        entries = [entry, dict(entry)]
    elif invalid == "extra_field":
        entry["unexpected"] = True
    else:
        entry["sha256"] = "A" * 64
    manifest = tmp_path / "invalid-binary.json"
    _write_json(manifest, {"entries": entries, "schema_version": 1})

    report = _scan_repository_policy(
        scanner,
        [],
        tmp_path,
        manifest,
        _empty_exemptions(tmp_path),
    )

    assert not report.ok
    assert report.findings[0][2].startswith(("BINARY_", "POLICY_"))


def _telegram_value(fill: str = "A") -> bytes:
    return ("123456:" + fill * 24).encode("ascii")


def _exemption(value: bytes, *, path: str, maximum: int = 1) -> dict[str, object]:
    return {
        "max_occurrences": maximum,
        "path": path,
        "purpose": "synthetic_detector_fixture",
        "rule_id": "TELEGRAM_TOKEN",
        "value_sha256": hashlib.sha256(value).hexdigest(),
    }


def test_exact_telegram_value_rule_path_and_occurrence_are_exempted(
    tmp_path: Path,
    scanner: ModuleType,
) -> None:
    relative = "backend/tests/fixture.py"
