@pytest.mark.parametrize("variant", ["wrong_path", "wrong_value", "same_context", "too_many"])
def test_telegram_exemption_cannot_suppress_neighboring_values_or_contexts(
    tmp_path: Path,
    scanner: ModuleType,
    variant: str,
) -> None:
    relative = "backend/tests/fixture.py"
    exempt = _telegram_value("A")
    observed = exempt
    source_relative = relative
    maximum = 1
    if variant == "wrong_path":
        source_relative = "backend/tests/other_fixture.py"
    elif variant in {"wrong_value", "same_context"}:
        observed = _telegram_value("Z")
    source = tmp_path / source_relative
    source.parent.mkdir(parents=True, exist_ok=True)
    prefix = b"# synthetic fictional fixture on the same line " if variant == "same_context" else b""
    occurrences = 2 if variant == "too_many" else 1
    source.write_bytes(prefix + b" ".join([observed] * occurrences) + b"\n")
    exemptions = tmp_path / "exemptions.json"
    _write_json(
        exemptions,
        {
            "exemptions": [_exemption(exempt, path=relative, maximum=maximum)],
            "schema_version": 1,
        },
    )

    report = _scan_repository_policy(
        scanner,
        [source],
        tmp_path,
        _empty_binaries(tmp_path),
        exemptions,
    )

    assert not report.ok
    assert "TELEGRAM_TOKEN" in {rule for _, _, rule in report.findings}
    assert observed.decode("ascii") not in repr(report.findings)


