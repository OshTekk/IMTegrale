def test_symlink_and_hardlink_never_reuse_binary_authorization(
    tmp_path: Path,
    scanner: ModuleType,
) -> None:
    payload = b"wOFF" + b"\x00" * 48
    original = tmp_path / "original.woff"
    original.write_bytes(payload)
    symlink = tmp_path / "symlink.woff"
    symlink.symlink_to(original)
    hardlink = tmp_path / "hardlink.woff"
    os.link(original, hardlink)
    manifest = tmp_path / "binary.json"
    _write_json(
        manifest,
        {
            "entries": [_binary_entry(payload, [hardlink.name, original.name, symlink.name])],
            "schema_version": 1,
        },
    )

    report = _scan_repository_policy(
        scanner,
        [symlink, hardlink],
        tmp_path,
        manifest,
        _empty_exemptions(tmp_path),
        enforce_unused=False,
    )

    assert not report.ok
    assert {rule for _, _, rule in report.findings} == {"HARDLINK_REJECTED", "SYMLINK_REJECTED"}
