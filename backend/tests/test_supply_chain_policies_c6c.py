ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = ROOT / "scripts"


def _load_scanner() -> ModuleType:
    if str(SCRIPTS) not in sys.path:
        sys.path.insert(0, str(SCRIPTS))
    path = SCRIPTS / "check_secrets.py"
    spec = importlib.util.spec_from_file_location("c6c_policy_scanner", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def scanner() -> ModuleType:
    return _load_scanner()


def _binary_entry(data: bytes, paths: list[str]) -> dict[str, object]:
    return {
        "allowed_paths": sorted(paths),
        "logical_type": "katex_font_woff",
        "media_type": "font/woff",
        "policy": "immutable_vendor_asset",
        "provenance": "Synthetic C6C digest policy test fixture.",
        "purpose": "immutable_vendor_asset",
        "review": "No production or student data; exact bytes generated by the test.",
        "scopes": ["repository"],
        "sha256": hashlib.sha256(data).hexdigest(),
        "size": len(data),
    }


def _write_json(path: Path, value: object) -> None:
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _empty_exemptions(tmp_path: Path) -> Path:
    path = tmp_path / "exemptions.json"
    _write_json(path, {"exemptions": [], "schema_version": 1})
    return path


def _empty_binaries(tmp_path: Path) -> Path:
    path = tmp_path / "binaries.json"
    _write_json(path, {"entries": [], "schema_version": 1})
    return path


def _scan_repository_policy(
    scanner: ModuleType,
    paths: list[Path],
    root: Path,
    binary_manifest: Path,
    exemptions_manifest: Path,
    *,
    enforce_unused: bool = True,
):  # noqa: ANN202
    return scanner.scan_paths_report(
        paths,
        root=root,
        policy_scope="repository",
        enforce_unused=enforce_unused,
        binary_allowlist_path=binary_manifest,
        secret_exemptions_path=exemptions_manifest,
    )


def test_exact_binary_digest_size_and_path_are_required(
    tmp_path: Path,
    scanner: ModuleType,
) -> None:
    payload = b"wOFF" + b"\x00" * 128
    source = tmp_path / "vendor.woff"
    source.write_bytes(payload)
    manifest = tmp_path / "binary.json"
    _write_json(manifest, {"entries": [_binary_entry(payload, [source.name])], "schema_version": 1})

    report = _scan_repository_policy(
        scanner,
        [source],
        tmp_path,
        manifest,
        _empty_exemptions(tmp_path),
    )

    assert report.ok
    assert report.binary_files_seen == 1
    assert report.binary_files_digest_allowlisted == 1
    assert report.binary_bytes_covered == len(payload)
    assert report.binary_regions_unscanned == 0
    assert report.unused_binary_allowlist_entries == 0


@pytest.mark.parametrize("mutation", ["one_byte", "size", "trailing"])
def test_any_binary_byte_or_size_change_is_rejected(
    tmp_path: Path,
    scanner: ModuleType,
    mutation: str,
) -> None:
    original = b"wOFF" + b"\x00" * 128
    source = tmp_path / "vendor.woff"
    changed = bytearray(original)
    if mutation == "one_byte":
        changed[-1] ^= 1
    elif mutation == "size":
        changed = changed[:-1]
    else:
        changed.extend(b"polyglot-trailer")
    source.write_bytes(changed)
    manifest = tmp_path / "binary.json"
    _write_json(manifest, {"entries": [_binary_entry(original, [source.name])], "schema_version": 1})

    report = _scan_repository_policy(
        scanner,
        [source],
        tmp_path,
        manifest,
        _empty_exemptions(tmp_path),
    )

    assert not report.ok
    assert report.binary_files_rejected == 1
    assert report.binary_files_digest_allowlisted == 0
    assert report.binary_regions_unscanned == 0


